import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const workspaceRoot = resolve(frontendRoot, '..')
const envText = await readFile(resolve(workspaceRoot, '.env'), 'utf8')

const values = new Map()
for (const rawLine of envText.split(/\r?\n/)) {
  const line = rawLine.trim()
  if (!line || line.startsWith('#')) continue
  const separator = line.indexOf('=')
  if (separator < 1) continue
  const name = line.slice(0, separator).trim()
  let value = line.slice(separator + 1).trim()
  if (
    value.length >= 2 &&
    ((value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'")))
  ) {
    value = value.slice(1, -1)
  }
  values.set(name, value)
}

const url = values.get('VITE_SUPABASE_URL') || values.get('SUPABASE_URL') || ''
const publishableKey =
  values.get('VITE_SUPABASE_PUBLISHABLE_KEY') ||
  values.get('SUPABASE_PUBLISHABLE_KEY') ||
  ''
const useLocalProxy = process.env.npm_lifecycle_event === 'predev'

const outputDir = resolve(frontendRoot, 'src', 'generated')
const outputPath = resolve(outputDir, 'public-config.ts')
const temporaryPath = `${outputPath}.tmp`
const source = [
  '// Generated by scripts/generate-public-config.mjs. Do not edit or commit.',
  `export const publicConfig = ${JSON.stringify({ url, publishableKey, useLocalProxy })} as const`,
  '',
].join('\n')

await mkdir(outputDir, { recursive: true })
await writeFile(temporaryPath, source, { encoding: 'utf8', mode: 0o600 })
await rename(temporaryPath, outputPath)
console.log('Generated public Supabase configuration.')
